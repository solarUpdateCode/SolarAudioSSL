#!/usr/bin/env bash
set -euo pipefail
VERSION="1.0.0"
BUILD_DIR="build/SolarAudioSSL_artefacts/Release"
DIST_DIR="dist"
STAGE_DIR="build/pkg_stage"
rm -rf "${DIST_DIR}" "${STAGE_DIR}"
mkdir -p "${DIST_DIR}" "${STAGE_DIR}/vst3" "${STAGE_DIR}/au" "${STAGE_DIR}/app"
cp -R "${BUILD_DIR}/VST3/SolarAudioSSL.vst3" "${STAGE_DIR}/vst3/"
cp -R "${BUILD_DIR}/AU/SolarAudioSSL.component" "${STAGE_DIR}/au/"
cp -R "${BUILD_DIR}/Standalone/SolarAudioSSL.app" "${STAGE_DIR}/app/"
pkgbuild --root "${STAGE_DIR}/vst3" --identifier "com.solaraudio.solaraudiossl.vst3" --version "${VERSION}" --install-location "/Library/Audio/Plug-Ins/VST3" "${DIST_DIR}/SolarAudioSSL_VST3.pkg"
pkgbuild --root "${STAGE_DIR}/au" --identifier "com.solaraudio.solaraudiossl.au" --version "${VERSION}" --install-location "/Library/Audio/Plug-Ins/Components" "${DIST_DIR}/SolarAudioSSL_AU.pkg"
pkgbuild --root "${STAGE_DIR}/app" --identifier "com.solaraudio.solaraudiossl.standalone" --version "${VERSION}" --install-location "/Applications" "${DIST_DIR}/SolarAudioSSL_Standalone.pkg"
productbuild --package "${DIST_DIR}/SolarAudioSSL_VST3.pkg" --package "${DIST_DIR}/SolarAudioSSL_AU.pkg" --package "${DIST_DIR}/SolarAudioSSL_Standalone.pkg" "${DIST_DIR}/SolarAudioSSL_${VERSION}_macOS_Installer.pkg"
echo "Built macOS installers in ${DIST_DIR}/"
